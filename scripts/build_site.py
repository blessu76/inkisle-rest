def lastmod_site(ctx):
    return max([p["published"].strftime("%Y-%m-%d") for p in ctx.posts] + [PAGES_UPDATED])


def lastmod_releases(ctx):
    return max([e["date"] for e in ctx.releases if e.get("date")] + [PAGES_UPDATED])


def sitemap_entries(ctx):
    """[(path, lastmod, {lang: path})]"""
    ents = []
    lm = lastmod_site(ctx)
    ents.append((path_home("en"), lm, {l: path_home(l) for l in ctx.langs}))
    for slug in ("about", "privacy"):
        ents.append((path_page("en", slug), PAGES_UPDATED, {l: path_page(l, slug) for l in ctx.langs if (l, slug) in ctx.pages}))
    for l in ctx.langs:
        if l == "en":
            continue
        ents.append((path_home(l), lm, {x: path_home(x) for x in ctx.langs}))
        for slug in ("about", "privacy"):
            if (l, slug) in ctx.pages:
                ents.append((path_page(l, slug), PAGES_UPDATED, {x: path_page(x, slug) for x in ctx.langs if (x, slug) in ctx.pages}))
    ents.append((path_releases("en"), lastmod_releases(ctx), {l: path_releases(l) for l in ctx.langs}))
    for l in ctx.langs:
        if l != "en":
            ents.append((path_releases(l), lastmod_releases(ctx), {x: path_releases(x) for x in ctx.langs}))
    for l in ctx.langs:
        n = len(posts_in(ctx, l))
        if n or l == "en":
            ents.append((path_journal(l), lm, {x: path_journal(x) for x in ctx.langs}))
            for pg in range(2, pages_count(n) + 1):
                ents.append((path_journal(l, pg), lm, {}))
    for p in ctx.posts:
        alts = {l: path_post(l, p["slug"]) for l in ctx.langs if l in p["langs"]}
        for l in alts:
            ents.append((alts[l], p["published"].strftime("%Y-%m-%d"), alts))
    return ents


def build_sitemap(ctx):
    rows = ['<?xml version="1.0" encoding="UTF-8"?>', "<!-- %s -->" % GEN_MARK,
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for pth, lm, alts in sitemap_entries(ctx):
        rows.append("<url><loc>%s</loc><lastmod>%s</lastmod>" % (esc(url(pth)), lm))
        if len(alts) > 1:
            for l, ap in alts.items():
                rows.append('<xhtml:link rel="alternate" hreflang="%s" href="%s"/>' % (l, esc(url(ap))))
            rows.append('<xhtml:link rel="alternate" hreflang="x-default" href="%s"/>' % esc(url(alts.get("en", next(iter(alts.values()))))))
        rows.append("</url>")
    rows.append("</urlset>")
    return "\n".join(rows) + "\n"


def build_robots():
    rows = ["# %s" % GEN_MARK, "User-agent: *", "Allow: /", ""]
    for b in BOTS:
        rows += ["User-agent: %s" % b, "Allow: /", ""]
    rows += ["Sitemap: %s/sitemap.xml" % SITE, ""]
    return "\n".join(rows)


