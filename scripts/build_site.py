def make_ctx(root, now=None, require_all=False):
    root = Path(root)
    now = now or dt.datetime.now(KST)
    i18n, errs = load_i18n(root)
    pages, e2 = load_pages(root)
    posts, e3 = load_posts(root, now)
    releases, e4 = load_releases(root)
    errs += e2 + e3 + e4 + queue_errors(root)
    langs = [l for l in LANGS if l in i18n and (l, "about") in pages and (l, "privacy") in pages]
    if "en" not in langs or "ko" not in langs:
        errs.append("en and ko must both be complete (i18n + about + privacy)")
    for l in LANGS:
        if l not in langs and require_all:
            errs.append("language %s is incomplete (needs i18n/%s.json, pages/%s/about.md, pages/%s/privacy.md)" % (l, l, l, l))
    for p in posts:
        if require_all:
            for l in LANGS:
                if l not in p["langs"]:
                    errs.append("%s: translation %s missing (--require-all)" % (p["slug"], l))
    for p in posts:
        p["langs"] = {l: v for l, v in p["langs"].items() if l in langs}
    posts = [p for p in posts if p["langs"]]
    return Ctx(root, i18n, pages, posts, langs, now, releases), errs


def build_all(ctx):
    """-> {relative file path: text}"""
    files = {}

    def put(path, text):
        files[path.lstrip("/") + "index.html" if path.endswith("/") else path.lstrip("/")] = text

    for l in ctx.langs:
        put(*build_home(ctx, l))
        for slug in ("about", "privacy"):
            put(*build_page(ctx, l, slug))
        put(*build_releases(ctx, l))
        for pg in range(1, pages_count(len(posts_in(ctx, l))) + 1):
            put(*build_list(ctx, l, pg))
        for p in ctx.posts:
            if l in p["langs"]:
                put(*build_post(ctx, l, p))
    files["404.html"] = build_404(ctx)
    files["sitemap.xml"] = build_sitemap(ctx)
    files["robots.txt"] = build_robots()
    files["llms.txt"] = build_llms(ctx)
    for l in ("en", "ko"):
        if l in ctx.langs:
            files[path_feed(l).lstrip("/")] = build_feed(ctx, l)
    return files


def clean(root):
    root = Path(root)
    for name in ["journal", "about", "privacy", "releases"] + [l for l in LANGS if l != "en"]:
        d = root / name
        if d.is_dir():
            shutil.rmtree(d)
    for name in ("index.html", "404.html", "sitemap.xml", "robots.txt", "llms.txt"):
        f = root / name
        if f.is_file():
            f.unlink()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    ap.add_argument("--check", action="store_true", help="validate sources only")
    ap.add_argument("--require-all", action="store_true", help="fail unless all 12 languages are complete for every post")
    a = ap.parse_args(argv)
    root = Path(a.root).resolve()
    ctx, errs = make_ctx(root, require_all=a.require_all)
    if errs:
        print("build_site: %d problem(s)\n  %s" % (len(errs), "\n  ".join(errs)), file=sys.stderr)
        return 1
    files = build_all(ctx)
    if a.check:
        print("build_site: sources OK — %d language(s), %d post(s), %d file(s) would be written" % (len(ctx.langs), len(ctx.posts), len(files)))
        return 0
    clean(root)
    for rel, text in files.items():
        f = root / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding="utf-8")
    print("build_site: wrote %d file(s) — %d language(s), %d post(s)" % (len(files), len(ctx.langs), len(ctx.posts)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
