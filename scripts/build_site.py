    grid = '<div class="grid">%s</div>' % "".join(post_card(ctx, lang, p, nums[p["slug"]]) for p in chunk) if chunk else '<p class="empty">%s</p>' % esc(t("empty"))
    pager = ""
    if total > 1:
        links = []
        if page > 1:
            links.append('<a rel="prev" href="%s">← %s</a>' % (esc(path_journal(lang, page - 1)), esc(t("prev"))))
        links.append("<span>%s %d / %d</span>" % (esc(t("page")), page, total))
