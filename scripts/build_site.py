class Ctx:
    def __init__(self, root, i18n, pages, posts, langs, now, releases=()):
        self.root, self.i18n, self.pages, self.posts, self.langs, self.now = root, i18n, pages, posts, langs, now
        self.releases = list(releases)

    def t(self, lang, key):
        return self.i18n[lang][key]

    def sub(self, lang, text):
        return (text.replace("{{OPERATOR}}", OPERATOR).replace("{{EMAIL}}", EMAIL).replace("{{EFFECTIVE}}", EFFECTIVE)
                .replace("{{SITE}}", SITE))

    def numbers(self):
        return {p["slug"]: i + 1 for i, p in enumerate(sorted(self.posts, key=lambda p: (p["published"], p["slug"])))}


